// Attribute the bytes of a built chunk back to their source modules.
import fs from 'node:fs';
import path from 'node:path';

const CHUNK = process.argv[2];
const LIMIT = Number(process.argv[3] || 40);

const map = JSON.parse(fs.readFileSync(CHUNK + '.map', 'utf8'));
const code = fs.readFileSync(CHUNK, 'utf8');
const lines = code.split('\n');

// --- minimal VLQ decoder ---
const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
const CHAR = {};
for (let i = 0; i < B64.length; i++) CHAR[B64[i]] = i;
function decodeVLQ(str) {
  const out = [];
  let i = 0;
  while (i < str.length) {
    let shift = 0, value = 0, cont = true;
    while (cont) {
      const d = CHAR[str[i++]];
      cont = (d & 32) !== 0;
      value += (d & 31) * 2 ** shift;
      shift += 5;
    }
    const neg = value & 1;
    value >>= 1;
    out.push(neg ? -value : value);
  }
  return out;
}

// --- decode mappings into positions ---
const segs = [];
let srcIdx = 0, srcLine = 0, srcCol = 0, nameIdx = 0;
map.mappings.split(';').forEach((lineStr, genLine) => {
  let genCol = 0;
  if (!lineStr) return;
  for (const seg of lineStr.split(',')) {
    if (!seg) continue;
    const f = decodeVLQ(seg);
    genCol += f[0];
    if (f.length > 1) {
      srcIdx += f[1];
      srcLine += f[2];
      srcCol += f[3];
      if (f.length > 4) nameIdx += f[4];
    }
    segs.push({ genLine, genCol, srcIdx, srcLine, srcCol });
  }
});

// --- bucket each generated byte range by source ---
const lineStart = [];
let acc = 0;
for (const l of lines) { lineStart.push(acc); acc += l.length + 1; }
const total = acc;

const bySource = new Map();
for (let i = 0; i < segs.length; i++) {
  const s = segs[i];
  const next = segs[i + 1];
  const start = lineStart[s.genLine] + s.genCol;
  const end = next ? lineStart[next.genLine] + next.genCol : total;
  const len = Math.max(0, end - start);
  const src = map.sources[s.srcIdx] || '(unknown)';
  bySource.set(src, (bySource.get(src) || 0) + len);
}

// group by package / directory
const groups = new Map();
for (const [src, len] of bySource) {
  let key;
  const nm = src.replace(/\\/g, '/');
  if (nm.includes('/node_modules/')) {
    const rest = nm.split('/node_modules/')[1];
    const parts = rest.split('/');
    key = 'node_modules/' + (parts[0].startsWith('@') ? parts[0] + '/' + parts[1] : parts[0]);
  } else if (nm.startsWith('../src/') || nm.startsWith('src/')) {
    key = 'src/' + nm.split('/src/')[1].split('/').slice(0, 2).join('/');
  } else {
    key = nm;
  }
  groups.set(key, (groups.get(key) || 0) + len);
}

const sorted = [...groups].sort((a, b) => b[1] - a[1]);
console.log(`\n=== ${path.basename(CHUNK)}  (${code.length} bytes) ===`);
for (const [k, v] of sorted.slice(0, LIMIT)) {
  console.log(String(v).padStart(9), (100 * v / code.length).toFixed(1).padStart(5) + '%', k);
}
console.log('\n--- top individual modules ---');
for (const [k, v] of [...bySource].sort((a, b) => b[1] - a[1]).slice(0, 25)) {
  console.log(String(v).padStart(9), k.replace(/\\/g, '/'));
}
